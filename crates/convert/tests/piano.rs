#[test]
fn freehand_remarks_survive_at_note_and_timed_direction_scope() {
    let input = score(&format!(
        "<direction><direction-type><words>Like distant bells — match the soloist</words></direction-type><voice>1</voice></direction>{}",
        note(
            "<footnote>Prefer the darker sample</footnote><voice>1</voice><notations><technical><other-technical>bowed-cloud texture; map manually</other-technical></technical><other-notation type=\"single\">irregular tremulous color</other-notation></notations>"
        )
    ));
    let c = convert::xml_to_midi2(&input, &RenderingPolicy::default()).unwrap();
    let d = clip::decode(&c.clip, Some(&c.companion.dictionary)).unwrap();
    assert!(
        d.events
            .iter()
            .filter_map(|e| remarks::performance(&e.words))
            .any(|(_, t)| t == "Like distant bells — match the soloist")
    );
    let values = remarks::literal_values(d.notes[0].descriptor.as_ref().unwrap());
    assert!(values.contains(&"Prefer the darker sample"));
    assert!(values.contains(&"bowed-cloud texture; map manually"));
    assert!(values.contains(&"irregular tremulous color"));
    let canonical = xml::write(&d).unwrap();
    support::assert_schema(
        &[canonical.as_bytes()],
        std::path::Path::new("piano/remarks inverse"),
    );
    assert!(canonical.contains("<footnote>Prefer the darker sample</footnote>"));
    assert!(canonical.contains("Like distant bells"));
    let (_, back) = xml::read(canonical.as_bytes(), &RenderingPolicy::default()).unwrap();
    let (bytes, map, _) = clip::encode(&back).unwrap();
    assert_eq!(
        d.semantic_values(),
        clip::decode(&bytes, Some(&map)).unwrap().semantic_values()
    );
    assert_eq!(d.notes[0].pitch, Rational::from_integer(60));
}

