fn piano_muffler_does_not_accept_a_brass_mute_identity(#[case] mute: &str, #[case] valid: bool) {
    let c = convert::xml_to_midi2(
        &score(&note(&format!("<play><mute>{mute}</mute></play>"))),
        &RenderingPolicy::default(),
    );
    if valid {
        let c = c.unwrap();
        let d = clip::decode(&c.clip, Some(&c.companion.dictionary)).unwrap();
        assert!(d.events.iter().any(|e| e.words
            == wire::registered_channel(
                Route::default(),
                0x41,
                0x20,
                if mute == "off" { 0 } else { u32::MAX }
            )));
    } else {
        assert_eq!(c.err().unwrap().code, "E_PIANO_MUTE");
    }
}

