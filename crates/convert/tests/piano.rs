#[test]
fn voice_scoped_text_survives_without_a_companion_and_stays_in_the_correct_part() {
    let input=b"<score-partwise version=\"4.0\"><part-list><score-part id=\"A\"><part-name>Violin</part-name></score-part><score-part id=\"B\"><part-name>Flute</part-name></score-part></part-list><part id=\"A\"><measure number=\"1\"><note><pitch><step>C</step><octave>4</octave></pitch><duration>1</duration></note></measure></part><part id=\"B\"><measure number=\"1\"><direction><direction-type><words>Follow only the second voice</words></direction-type><voice>2</voice></direction><note><pitch><step>D</step><octave>4</octave></pitch><duration>1</duration><voice>2</voice></note></measure></part></score-partwise>";
    let c = convert::xml_to_midi2(input, &RenderingPolicy::default()).unwrap();
    let d = clip::decode(&c.clip, Some(&c.companion.dictionary)).unwrap();
    assert_eq!(
        d.notes[1].descriptor.as_ref().unwrap().qualifiers[remarks::CONTEXT]["voice"],
        "2"
    );
    let event = d
        .events
        .iter()
        .find(|e| remarks::scope(&e.words).is_some())
        .unwrap();
    assert_eq!(remarks::scope(&event.words).unwrap()["voice"], "2");
    let canonical = xml::write(&d).unwrap();
    support::assert_schema(
        &[canonical.as_bytes()],
        std::path::Path::new("piano/remarks inverse"),
    );
    let doc = roxmltree::Document::parse(&canonical).unwrap();
    let words = doc
        .descendants()
        .find(|n| n.has_tag_name("words") && n.text() == Some("Follow only the second voice"))
        .unwrap();
    let part = words.ancestors().find(|n| n.has_tag_name("part")).unwrap();
    assert_eq!(part.attribute("id"), Some("P1"));
    assert!(part.descendants().any(|n| {
        n.has_tag_name("note")
            && n.children()
                .any(|v| v.has_tag_name("voice") && v.text() == Some("2"))
    }));
    assert!(
        words
            .ancestors()
            .find(|n| n.has_tag_name("direction"))
            .unwrap()
            .children()
            .any(|n| n.has_tag_name("voice") && n.text() == Some("2"))
    );
    let (_, back) = xml::read(canonical.as_bytes(), &RenderingPolicy::default()).unwrap();
    let (bytes, map, _) = clip::encode(&back).unwrap();
    assert_eq!(
        d.semantic_values(),
        clip::decode(&bytes, Some(&map)).unwrap().semantic_values()
    );
}

#[test]
fn ordinary_piano_declares_only_piano_and_emits_no_orchestral_attribute() {
    let c = convert::xml_to_midi2(&score(&note("")), &RenderingPolicy::default()).unwrap();
    assert_eq!(
        c.companion.requirements["profiles"][0]["profileIds"],
        serde_json::json!([[0x7e, 0x20, 0, 1, 1]])
    );
    // Literal packet, independently specified: C4, no Attribute, Piano mf hammer.
    let vector = [0x40, 0x90, 0x3c, 0x00, 0x9e, 0x79, 0x00, 0x00];
    assert!(c.clip[8..].windows(8).any(|b| b == vector));
    assert!(
        !c.clip[8..]
            .windows(4)
            .any(|b| b == [0x40, 0x90, 0x3c, 0x10])
    );
    let d = clip::decode(&c.clip, Some(&c.companion.dictionary)).unwrap();
    assert!(
        d.required_features(None)
            .unwrap()
            .standard
            .iter()
            .all(|n| *n == 0)
    );
    let short = convert::xml_to_midi2(
        &score(&note(
            "<notations><articulations><staccato/></articulations></notations>",
        )),
        &RenderingPolicy::default(),
    )
    .unwrap();
    assert_eq!(
        short.companion.requirements["profiles"][0]["profileIds"],
        serde_json::json!([[0x7e, 0x20, 0, 1, 1], [0x7e, 0x21, 1, 1, 1]])
    );
    assert!(
        short.clip[8..]
            .windows(4)
            .any(|b| b == [0x40, 0x90, 0x3c, 0x11])
    );
    assert!(wire::validate(&[0x4090_3c04]).is_err());
}

