fn piano_key_velocity_and_optional_position_controllers_use_standard_fields() {
    assert_eq!(
        piano::note(Route::default(), 60, 0xb8e3, Some(0x6a00), true).unwrap(),
        [0x4090_3c04, 0xb8e3_6a00]
    );
    assert_eq!(
        piano::note(Route::default(), 60, 0x8000, None, false).unwrap(),
        [0x4080_3c00, 0x8000_0000]
    );
    wire::validate(&[0x4090_3c04, 0xb8e3_6a00]).unwrap();
    for index in 13..=15 {
        wire::validate(&wire::controller(
            Route::default(),
            60,
            index,
            0x8000_0000,
            true,
        ))
        .unwrap();
    }
}
#[test]
fn piano_ci_uses_its_published_id_and_31_byte_details() {
    assert_eq!(piano::PROFILE_ID, [0x7e, 0x20, 0, 1, 1]);
    let mut a = ci::Engine::new_piano(1).unwrap();
    let mut b = ci::Engine::new_piano(2).unwrap();
    let enable = a.request_enable(2, 0, 100).unwrap();
    assert!(matches!(
        enable.body,
        ci::Body::Set {
            profile: piano::PROFILE_ID,
            ..
        }
    ));
    for reply in b.receive(&enable).unwrap() {
        a.receive(&reply).unwrap();
    }
    assert!(a.remote[&(2, 0)]);
    let query = a.request_details(2, 0, 0x40, 100).unwrap();
    for reply in b.receive(&query).unwrap() {
        a.receive(&reply).unwrap();
    }
    assert_eq!(a.piano_details[&(2, 0)].len(), 31);
    assert_eq!(a.piano_details[&(2, 0)][0], 1); // converter Sender; no fictitious sound engine
    a.invalidate_program(2, 0);
    assert!(!a.piano_details.contains_key(&(2, 0)));
    assert!(a.request_details(2, 0, 1, 100).is_err());
    let mut invalid = piano::sender_details();
    invalid[0] |= 8;
    assert!(piano::validate_details(&invalid).is_err());
}
#[rstest]
#[case::invalidation(false)]
#[case::discovery_collision(true)]
fn local_identity_renewal_discards_piano_capabilities(#[case] discovery_collision: bool) {
    use rand::SeedableRng;
    let mut client = ci::Engine::new_piano(1).unwrap();
    let mut peer = ci::Engine::new_piano(2).unwrap();
    client.enabled.insert(0);
    let query = client.request_details(2, 0, 0x40, 100).unwrap();
    for reply in peer.receive(&query).unwrap() {
        client.receive(&reply).unwrap();
    }
    assert_eq!(client.piano_details[&(2, 0)], piano::sender_details());
    let payload = if discovery_collision {
        client.discovery()
    } else {
        ci::Message {
            address: midi2::ci::DeviceId::FunctionBlock,
            version: 2,
            source: peer.muid,
            destination: midi2::ux::u28::new(ci::BROADCAST),
            body: ci::Body::Invalidate { muid: 1 },
        }
        .encode()
        .unwrap()
    };
    client
        .receive_payload_with_rng(&payload, &mut rand::rngs::StdRng::seed_from_u64(42))
        .unwrap();
    assert_ne!(u32::from(client.muid), 1);
    assert!(client.enabled.contains(&0));
    assert!(client.piano_details.is_empty());
}
