#[case("pppp", 0x1400)]
#[case("ppp", 0x3200)]
#[case("pp", 0x5000)]
#[case("p", 0x6a00)]
#[case("mp", 0x8410)]
#[case("mf", 0x9e79)]
#[case("f", 0xb8e3)]
#[case("ff", 0xd145)]
#[case("fff", 0xebae)]
#[case("ffff", 0xfbef)]
fn published_piano_dynamic_centers(#[case] mark: &str, #[case] expected: u16) {
    // Independent literals from M2-126 Table 6, not values generated by the encoder.
    assert_eq!(
        rules::upscale(u32::try_from(piano::dynamic(mark).unwrap()).unwrap(), 7, 16),
        u32::from(expected)
    );
    let input = score(&format!(
        "<direction><direction-type><dynamics><{mark}/></dynamics></direction-type></direction>{}",
        note("")
    ));
    let c = convert::xml_to_midi2(&input, &RenderingPolicy::default()).unwrap();
    let d = clip::decode(&c.clip, Some(&c.companion.dictionary)).unwrap();
    assert_eq!(d.notes[0].velocity, expected);
    assert_eq!(
        d.piano_routes,
        std::collections::BTreeSet::from([Route::default()])
    );
    let canonical = xml::write(&d).unwrap();
    support::assert_schema(
        &[canonical.as_bytes()],
        std::path::Path::new("piano/remarks inverse"),
    );
    let (_, back) = xml::read(canonical.as_bytes(), &RenderingPolicy::default()).unwrap();
    let (bytes, map, _) = clip::encode(&back).unwrap();
    assert_eq!(
        d.semantic_values(),
        clip::decode(&bytes, Some(&map)).unwrap().semantic_values()
    );
}
