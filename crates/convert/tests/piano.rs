fn score(body: &str) -> Vec<u8> {
    format!("<score-partwise version=\"4.0\"><part-list><score-part id=\"P1\"><part-name>Piano</part-name><score-instrument id=\"I1\"><instrument-name>Grand Piano</instrument-name><instrument-sound>keyboard.piano</instrument-sound></score-instrument></score-part></part-list><part id=\"P1\"><measure number=\"1\"><attributes><divisions>4</divisions></attributes>{body}</measure></part></score-partwise>").into_bytes()
}
fn note(extra: &str) -> String {
    format!(
        "<note><pitch><step>C</step><octave>4</octave></pitch><duration>4</duration>{extra}</note>"
    )
}
